//! Build-time keycode-table codegen, invoked by `build.rs`.
//!
//! `KEYS` is the single source of truth for the input device's physical-key
//! table: winit `KeyCode` variant names in id order, an entry's index being
//! the `u16` that crosses the `ely:input` boundary. From it this emits
//! `$OUT_DIR/keys.rs` — the `Key` enum, `Key::COUNT`, and
//! `Key::from_key_code` — `include!`d by `kernel/input/keys.rs`, and
//! rewrites the generated `Key` blocks in `kernel/runtime_modules/input.ts`
//! and `userland/elysium.d.ts`.

