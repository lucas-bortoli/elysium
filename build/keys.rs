pub fn generate(out_dir: &Path) {
    generate_rust(out_dir);
    generate_ts();
    generate_dts();
}

fn generate_rust(out_dir: &Path) {
    let mut s =
        String::from("// @generated by build/keys.rs from its KEYS table — do not edit.\n\n");
    s.push_str(
        "/// One physical key, identified by position rather than the character it\n\
         /// produces. `#[repr(u16)]` with explicit discriminants because the value\n\
         /// *is* the wire format crossing the `ely:input` boundary; variants are\n\
         /// built from that id via `Key::from_id`, seldom named in Rust, hence\n\
         /// `#[allow(dead_code)]`.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n\
         #[repr(u16)]\n\
         #[allow(dead_code)]\n\
         pub enum Key {\n",
    );
    for (id, name) in KEYS.iter().enumerate() {
        writeln!(s, "    {name} = {id},").unwrap();
    }
    s.push_str("}\n\n");
    s.push_str("impl Key {\n");
    s.push_str("    /// Number of variants — valid discriminants are exactly `0..COUNT`.\n");
    writeln!(s, "    pub const COUNT: usize = {};\n", KEYS.len()).unwrap();
    s.push_str(
        "    /// Translates a winit physical key code into the matching `Key`, or\n\
         \x20   /// `None` for a code this enum has no entry for (`KeyCode` is\n\
         \x20   /// `#[non_exhaustive]`, so winit may add variants this match doesn't\n\
         \x20   /// know yet).\n\
         \x20   pub fn from_key_code(code: winit::keyboard::KeyCode) -> Option<Key> {\n\
         \x20       match code {\n",
    );
    for name in KEYS {
        writeln!(
            s,
            "            winit::keyboard::KeyCode::{name} => Some(Key::{name}),"
        )
        .unwrap();
    }
    s.push_str("            _ => None,\n        }\n    }\n}\n");

    std::fs::write(out_dir.join("keys.rs"), s).unwrap();
}

fn generate_ts() {
    let mut body = String::from("export const Key = {\n");
    for (id, name) in KEYS.iter().enumerate() {
        writeln!(body, "  {name}: {id},").unwrap();
    }
    body.push_str("} as const;\n");
    rewrite_between_markers(Path::new("kernel/runtime_modules/input.ts"), "keys", &body);
}

fn generate_dts() {
    let mut body = String::from("  export const Key: {\n");
    for (id, name) in KEYS.iter().enumerate() {
        writeln!(body, "    readonly {name}: {id};").unwrap();
    }
    body.push_str("  };\n");
    rewrite_between_markers(Path::new("userland/elysium.d.ts"), "keys", &body);
}
