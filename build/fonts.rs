//! Build-time BDF -> packed bitmap font codegen, invoked by `build.rs`.
//!
//! Each configured font's BDF is parsed once here, at build time, rather
//! than at every boot: BDF is a verbose ASCII format with fussy per-glyph
//! metrics, and the kernel only ever needs the finished bitmap. We keep
//! just the requested codepoint ranges and write `$OUT_DIR/fonts.rs` — a
//! set of `FontData`/`Glyph` literals the kernel `include!`s. The BDF's own
//! one-bit-per-pixel row packing is kept verbatim; nothing here expands it.
//!
//! Anything malformed (a glyph whose `BITMAP` doesn't match its `BBX`, a
//! requested codepoint the BDF lacks) panics, which fails `cargo build`
//! with a message rather than producing a subtly wrong font — build-script
//! submodules can't be reached by `cargo test`, so these asserts stand in
//! for unit tests of the parser.

use std::fmt::Write as _;
use std::ops::RangeInclusive;
use std::path::Path;

struct FontSpec {
    /// Also the identifier stem for the generated glyph slice and the
    /// `name` field the kernel exposes.
    name: &'static str,
    path: &'static str,
    /// Codepoint ranges to bake in. Explicit so a full-Unicode BDF doesn't
    /// drag thousands of unused glyphs into the binary.
    ranges: &'static [RangeInclusive<u32>],
}

/// Fonts baked into the kernel. An entry's index in this slice is the font
/// id that crosses the `ely:framebuffer` boundary. Kept in sync by hand with
/// `Font` in `kernel/runtime_modules/framebuffer.ts` and its mirror in
/// `userland/elysium.d.ts` — the palette solves the same problem by
/// generating all three copies from one table
/// (`kernel/framebuffer/palette.rs`), which is where this should go if the
/// list ever grows past one font.
const FONTS: &[FontSpec] = &[FontSpec {
    name: "cozette",
    path: "kernel/text/cozette.bdf",
    ranges: &[0x20..=0x7E], // ASCII printable
}];

const STRUCTS: &str = "\
pub struct Glyph {
    pub codepoint: u32,
    pub advance: u16,
    pub w: u8,
    pub h: u8,
    pub x_off: i8,
    pub y_off: i8,
    pub bits: &'static [u8],
}

#[allow(dead_code)] // `name`/`descent` are carried for completeness.
pub struct FontData {
    pub name: &'static str,
    pub ascent: i32,
    pub descent: i32,
    pub line_height: u32,
    pub default_advance: u16,
    pub glyphs: &'static [Glyph],
}

";

pub fn generate(out_dir: &Path) {
    let mut glyph_slices = String::new();
    let mut font_rows = String::new();

    for spec in FONTS {
        println!("cargo:rerun-if-changed={}", spec.path);
        let src = std::fs::read_to_string(spec.path)
            .unwrap_or_else(|e| panic!("font {}: reading {}: {e}", spec.name, spec.path));
        let font = parse_bdf(spec, &src);

        let ident = spec.name.to_uppercase();
        writeln!(glyph_slices, "static {ident}_GLYPHS: &[Glyph] = &[").unwrap();
        for g in &font.glyphs {
            writeln!(
                glyph_slices,
                "    Glyph {{ codepoint: {}, advance: {}, w: {}, h: {}, x_off: {}, y_off: {}, bits: &{:?} }},",
                g.codepoint, g.advance, g.w, g.h, g.x_off, g.y_off, g.bits,
            )
            .unwrap();
        }
        glyph_slices.push_str("];\n\n");

        writeln!(
            font_rows,
            "    FontData {{ name: {:?}, ascent: {}, descent: {}, line_height: {}, default_advance: {}, glyphs: {ident}_GLYPHS }},",
            spec.name, font.ascent, font.descent, font.line_height, font.default_advance,
        )
        .unwrap();
    }

    let mut out = String::from("// @generated by build/fonts.rs — do not edit.\n\n");
    out.push_str(STRUCTS);
    out.push_str(&glyph_slices);
    out.push_str("pub static FONTS: &[FontData] = &[\n");
    out.push_str(&font_rows);
    out.push_str("];\n");

    std::fs::write(out_dir.join("fonts.rs"), out).unwrap();
}

struct ParsedGlyph {
    codepoint: u32,
    advance: u16,
    w: u8,
    h: u8,
    x_off: i8,
    y_off: i8,
    bits: Vec<u8>,
}

struct ParsedFont {
    ascent: i32,
    descent: i32,
    line_height: u32,
    default_advance: u16,
    glyphs: Vec<ParsedGlyph>,
}

fn wanted(spec: &FontSpec, cp: u32) -> bool {
    spec.ranges.iter().any(|r| r.contains(&cp))
}

fn parse_bdf(spec: &FontSpec, src: &str) -> ParsedFont {
    let name = spec.name;

    let mut font_ascent: Option<i32> = None;
    let mut font_descent: Option<i32> = None;
    let mut bbox_w: Option<i32> = None;
    let mut bbox_h: Option<i32> = None;
    let mut bbox_yoff: Option<i32> = None;

    let mut glyphs: Vec<ParsedGlyph> = Vec::new();

    // Per-glyph accumulators, reset at each ENDCHAR.
    let mut cur_encoding: Option<i64> = None;
    let mut cur_advance: Option<u16> = None;
    let mut cur_bbx: Option<(i32, i32, i32, i32)> = None; // w, h, x_off, y_off
    let mut in_bitmap = false;
    let mut bitmap: Vec<u8> = Vec::new();

    for raw in src.lines() {
        let line = raw.trim_end_matches('\r');
        let mut it = line.split_whitespace();
        let Some(tok) = it.next() else { continue };

        match tok {
            "FONT_ASCENT" => font_ascent = it.next().and_then(|v| v.parse().ok()),
            "FONT_DESCENT" => font_descent = it.next().and_then(|v| v.parse().ok()),
            "FONTBOUNDINGBOX" => {
                let n: Vec<i32> = it.filter_map(|v| v.parse().ok()).collect();
                assert!(
                    n.len() == 4,
                    "font {name}: malformed FONTBOUNDINGBOX: {line:?}"
                );
                bbox_w = Some(n[0]);
                bbox_h = Some(n[1]);
                bbox_yoff = Some(n[3]);
            }
            "ENCODING" => cur_encoding = it.next().and_then(|v| v.parse().ok()),
            "DWIDTH" => {
                cur_advance = it
                    .next()
                    .and_then(|v| v.parse::<i32>().ok())
                    .map(|v| v.max(0) as u16);
            }
            "BBX" => {
                let n: Vec<i32> = it.filter_map(|v| v.parse().ok()).collect();
                assert!(n.len() == 4, "font {name}: malformed BBX: {line:?}");
                cur_bbx = Some((n[0], n[1], n[2], n[3]));
            }
            "BITMAP" => {
                in_bitmap = true;
                bitmap.clear();
            }
            "ENDCHAR" => {
                in_bitmap = false;
                let encoding = cur_encoding.take().unwrap_or(-1);
                let bbx = cur_bbx.take();
                let advance = cur_advance.take();
                let rows = std::mem::take(&mut bitmap);

                if encoding >= 0 && wanted(spec, encoding as u32) {
                    let (w, h, x_off, y_off) =
                        bbx.unwrap_or_else(|| panic!("font {name}: glyph {encoding} has no BBX"));
                    let advance = advance
                        .unwrap_or_else(|| panic!("font {name}: glyph {encoding} has no DWIDTH"));
                    let row_bytes = (w.max(0) as usize).div_ceil(8);
                    let expected = row_bytes * h.max(0) as usize;
                    assert_eq!(
                        rows.len(),
                        expected,
                        "font {name}: glyph {encoding}: BITMAP has {} bytes, expected {expected} for a {w}x{h} cell",
                        rows.len(),
                    );
                    glyphs.push(ParsedGlyph {
                        codepoint: encoding as u32,
                        advance,
                        w: u8::try_from(w).expect("glyph wider than 255px"),
                        h: u8::try_from(h).expect("glyph taller than 255px"),
                        x_off: i8::try_from(x_off).expect("glyph x offset out of range"),
                        y_off: i8::try_from(y_off).expect("glyph y offset out of range"),
                        bits: rows,
                    });
                }
            }
            _ if in_bitmap => {
                // A BITMAP data row: a run of hex digits, one glyph row.
                assert!(
                    tok.len() % 2 == 0,
                    "font {name}: odd-length BITMAP row {tok:?}",
                );
                for i in (0..tok.len()).step_by(2) {
                    let byte = u8::from_str_radix(&tok[i..i + 2], 16)
                        .unwrap_or_else(|_| panic!("font {name}: bad hex in BITMAP row {tok:?}"));
                    bitmap.push(byte);
                }
            }
            _ => {}
        }
    }

    let (ascent, descent) = match (font_ascent, font_descent) {
        (Some(a), Some(d)) => (a, d),
        _ => {
            let h = bbox_h.unwrap_or_else(|| {
                panic!("font {name}: has neither FONT_ASCENT/FONT_DESCENT nor FONTBOUNDINGBOX")
            });
            let y = bbox_yoff.expect("checked alongside bbox_h");
            (h + y, -y)
        }
    };
    let line_height = (ascent + descent).max(0) as u32;

    // Advance used for a codepoint with no glyph: the space's advance if the
    // font has one, else the bounding-box width.
    let default_advance = glyphs
        .iter()
        .find(|g| g.codepoint == 0x20)
        .map(|g| g.advance)
        .or_else(|| bbox_w.map(|w| w.max(0) as u16))
        .unwrap_or(0);

    for range in spec.ranges {
        for cp in range.clone() {
            assert!(
                glyphs.iter().any(|g| g.codepoint == cp),
                "font {name}: BDF is missing requested codepoint {cp:#x}",
            );
        }
    }
    glyphs.sort_by_key(|g| g.codepoint);

    ParsedFont {
        ascent,
        descent,
        line_height,
        default_advance,
        glyphs,
    }
}
